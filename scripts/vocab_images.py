# Prefer longer keys first when matching
_KEYWORD_KEYS = sorted(KEYWORD_IMAGES.keys(), key=len, reverse=True)


def _tokens_from_meaning(text: str) -> list[str]:
    if not text:
        return []
    cleaned = text.lower()
    cleaned = re.sub(r"\([^)]*\)", " ", cleaned)
    parts = re.split(r"[;,/|]+", cleaned)
    out: list[str] = []
    for part in parts:
        part = re.sub(r"^to\s+", "", part.strip())
        part = re.sub(r"[^a-z0-9\s\-']", " ", part)
        part = re.sub(r"\s+", " ", part).strip()
        if part:
            out.append(part)
            # also first word
            first = part.split()[0]
            if first and first != part:
                out.append(first)
    return out


def resolve_image_url(
    hanzi: str,
    meaning_en: Optional[str] = None,
    meaning_vi: Optional[str] = None,
) -> Optional[str]:
    if hanzi in HANZI_IMAGES:
        return HANZI_IMAGES[hanzi]

    blob = f"{meaning_en or ''} {meaning_vi or ''}".lower()
    for key in _KEYWORD_KEYS:
        if len(key) <= 3:
            if re.search(rf"(^|[^a-z]){re.escape(key)}([^a-z]|$)", blob):
                return KEYWORD_IMAGES[key]
        elif key in blob:
            return KEYWORD_IMAGES[key]

    for token in _tokens_from_meaning(meaning_en or ""):
        if token in KEYWORD_IMAGES:
            return KEYWORD_IMAGES[token]
        for key in _KEYWORD_KEYS:
            if len(key) >= 4 and len(token) >= 4 and (token.startswith(key) or key.startswith(token)):
                return KEYWORD_IMAGES[key]

    return None
